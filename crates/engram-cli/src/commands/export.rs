//! `engram export` — dump the source-of-truth store as JSON to stdout.
//!
//! Format version 2 exports everything needed for a lossless restore: KBs,
//! documents, memories (with their KB), chunks (with embeddings, base64),
//! and facts (with supersession history). Derived tables — claims, entities,
//! relations, wiki pages, source spans — are compiler caches; run
//! `engram compile --all` after import to regenerate them.

use crate::context::AppContext;
use crate::error::CliError;
use crate::output::{print_success, Metadata};
use serde_json::json;

pub fn run(ctx: &AppContext, format: String, kb: Option<String>) -> Result<(), CliError> {
    if format != "json" {
        return Err(CliError::BadInput(format!(
            "unknown format: {format} (only json supported)"
        )));
    }
    let kb_filter = kb.as_deref();
    let kbs = ctx.store.export_kbs(kb_filter)?;
    let documents = ctx.store.export_documents(kb_filter)?;
    let memories = ctx.store.export_memories(kb_filter)?;
    let chunks = ctx.store.export_chunks(kb_filter)?;
    let facts = ctx.store.export_facts(kb_filter)?;

    let payload = json!({
        "version": 2,
        "kb": kb,
        "counts": {
            "kbs": kbs.len(),
            "documents": documents.len(),
            "memories": memories.len(),
            "chunks": chunks.len(),
            "facts": facts.len(),
        },
        "derived": "claims/entities/relations/wiki are regenerated by `engram compile --all` after import",
        "kbs": kbs,
        "documents": documents,
        "memories": memories,
        "chunks": chunks,
        "facts": facts,
    });
    let mut meta = Metadata::default();
    meta.add("memories", memories.len());
    meta.add("chunks", chunks.len());
    meta.add("documents", documents.len());
    meta.add("facts", facts.len());
    print_success(ctx.format, payload, meta, |data| {
        println!("{}", serde_json::to_string(data).unwrap())
    });
    Ok(())
}
