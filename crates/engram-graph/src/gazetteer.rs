//! A compact built-in gazetteer: the names that are never humans.
//!
//! The capitalization-driven extractor cannot tell "Noemi" from "Ibiza" — both
//! are single Title-Case tokens sitting next to interpersonal cues ("we met in
//! Ibiza", "Islam came up over dinner"). Compiling a real personal store
//! therefore produced `person` nodes called London (84 mentions), Ibiza (49),
//! Singapore (48) and Islam (32), which is worse than no person graph at all:
//! they outrank real contacts in `people list` and drag co-occurrence edges
//! onto everyone who ever mentioned a holiday.
//!
//! So this module holds three data-driven lists, all matched case-insensitively:
//!
//! - [`PLACES`] — countries, regions and the cities that turn up in ordinary
//!   personal correspondence. A candidate whose WHOLE name is a place is never
//!   typed as a person.
//! - [`CREEDS_AND_PEOPLES`] — religions, languages, nationalities and the major
//!   holidays. Same rule.
//! - [`CONTACT_LABEL_WORDS`] — the company/topic words that betray a messaging
//!   app contact label ("Maria Microsoft London Tech"). These are rejected as
//!   NAME TOKENS, so a label can never be a person however it is capitalized.
//!
//! ## Deliberate omissions — read before adding entries
//!
//! Matching is on the WHOLE candidate name, so a place word inside a longer
//! name is harmless ("Jordan Peterson" survives). But a bare given name that
//! is also a place would be refused person typing, so common given names are
//! kept OUT of the list on purpose: Milan, Sofia, Jordan, Georgia, Austin,
//! Sydney, Victoria, Charlotte, Florence, Alexandria, Phoenix, Chelsea,
//! Brooklyn, Savannah, Dakota, Asia, Christian, Roman. Losing "Milan the city"
//! as an entity costs a co-occurrence edge; losing "Milan the Serbian friend"
//! costs a person. Extend the lists freely — just apply that test first.

